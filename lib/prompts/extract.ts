const RULES = `규칙:
- 영어 지문 본문만 옮깁니다. 한국어 발문("다음 글의 주제로…"), 선택지 ①~⑤, 각주(*표시 어휘 풀이), 페이지 번호, 머리글은 제외합니다.
- 한 글자도 고치거나 요약하지 말고 보이는 그대로 적습니다. 철자 오류도 그대로 둡니다.
- 밑줄 번호(①, ② 등)나 (A)/(B) 표시는 빼고 그 단어만 남깁니다. 빈칸은 "_____" 로 둡니다.
- 줄 끝에서 하이픈으로 끊긴 단어는 이어서 적습니다.
- 서로 다른 문항의 지문은 반드시 따로 나눕니다. 한 지문이 쪽(사진)을 넘어가면 이어 붙여 하나로 만듭니다.
- 순서배열 문제처럼 (A)(B)(C)로 나뉜 지문은 주어진 글 + (A)(B)(C)를 원래 순서대로 이어 하나의 지문으로 만들고 warnings 에 알려 주세요. 원래 순서를 모르면 보이는 순서대로 둡니다.
- 문장삽입 문제의 "주어진 문장"은 지문 속 원래 자리에 넣어 하나의 지문으로 만들고 warnings 에 알려 주세요.
- label: 문항 번호가 보이면 그 숫자(예: "18"), 없으면 "".
- 글자가 흐려 확실하지 않은 단어는 가장 그럴듯하게 적고, 그 지문의 warnings 에 한국어로 알려 주세요.
- 영어 지문이 없으면 passages 를 [] 로 둡니다.
- 지문은 나온 순서대로 최대 10개까지 옮깁니다. 더 있으면 전체 warnings 에 알려 주세요.`;

const FORMAT = `JSON만 출력:
{"passages":[{"label":"18","passage":"...","warnings":["3번째 줄 'acquire'가 흐려서 추정했습니다"]},{"label":"19","passage":"...","warnings":[]}],"warnings":[]}`;

/** 사진·PDF용 */
export const EXTRACT_PROMPT = `첨부한 사진(또는 PDF)에서 영어 지문을 모두 찾아, 지문마다 본문만 그대로 옮겨 적으세요. 사진이 여러 장이면 첨부 순서대로 이어서 봅니다.

${RULES}

${FORMAT}`;

/** 붙여 넣은 긴 텍스트용 */
export function splitTextPrompt(text: string): string {
  return `아래 텍스트에는 영어 지문이 여러 개 섞여 있을 수 있습니다. 지문마다 나누어 본문만 그대로 옮겨 적으세요.

<text>
${text}
</text>

${RULES}

${FORMAT}`;
}
